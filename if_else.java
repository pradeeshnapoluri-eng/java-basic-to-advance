public class if_else {
    public static void main(String args[]){
        int a = 20;
        int b = 15;
        if (a > b && a >= b)
        {
            System.out.println("A is greater than "+b);
        }
        else if (a <= b){
            System.out.println("A is less/or equal to B");
        }
        else {
            System.out.println("A is not B");
        }
    }
 }
    

