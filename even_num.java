public class even_num {
    public static void main(String[] args){
        for(int i=0;i <= 100;i++) {
            if (i % 2 ==0 ) {
                System.out.println("the even nums are:"+i);
            } else {
                System.out.println("the odd nums are:"+i);
            }
        }
     }
    }
    
    

